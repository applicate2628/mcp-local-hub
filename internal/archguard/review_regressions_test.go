func TestGlobPatternsUsedByRepositoryPolicy(t *testing.T) {
	tests := []struct {
		pattern string
		value   string
		want    bool
	}{
		{"internal/api/**/*_test.go", "internal/api/install_test.go", true},
		{"internal/api/**/*_test.go", "internal/api/sub/install_test.go", true},
		{"internal/api/**/*_test.go", "internal/api/install.go", false},
		{"**/*_test.go", "x_test.go", true},
		{"**/*_test.go", "internal/x/x_test.go", true},
		{"**/testdata/**", "internal/x/testdata/fixture.go", true},
	}
	for _, tc := range tests {
		if got := matchGlob(tc.pattern, tc.value); got != tc.want {
			t.Errorf("matchGlob(%q, %q)=%v, want %v", tc.pattern, tc.value, got, tc.want)
		}
	}
}

