func TestFileBudgetFingerprintSurvivesThresholdClassChange(t *testing.T) {
	fingerprint := func(lines int) string {
		root := newFixtureRepo(t, map[string]string{
			"internal/x/x.go": "package x\n" + strings.Repeat("\n", lines-1),
		})
		p := mustLoadPolicyForTest(t)
		p.SourceRoots = []string{"internal"}
		p.FileBudgets = FileBudgets{ProductionAdvisoryLines: 2, ProductionHardLines: 4, TestReviewLines: 4}
		got := violationsOfKind(mustScan(t, root, p), KindFileBudget)
		if len(got) != 1 {
			t.Fatalf("lines=%d got=%#v", lines, got)
		}
		return got[0].Fingerprint
	}
	if got, want := fingerprint(3), fingerprint(5); got != want {
		t.Fatalf("threshold class changed fingerprint: got=%s want=%s", got, want)
	}
}

