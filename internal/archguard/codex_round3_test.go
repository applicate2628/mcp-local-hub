func TestScanRejectsPolicyModuleMismatch(t *testing.T) {
	root := newFixtureRepo(t, map[string]string{
		"internal/x/x.go": "package x\n",
	})
	policy := mustLoadPolicyForTest(t)
	policy.SourceRoots = []string{"internal"}
	policy.Module = "wrong-module"
	_, err := Scan(t.Context(), ScanOptions{Root: root, Policy: policy})
	if err == nil || !strings.Contains(err.Error(), "policy module") || !strings.Contains(err.Error(), "mcp-local-hub") {
		t.Fatalf("error=%v, want policy/go.mod module mismatch", err)
	}
}

func TestUnaliasedLocalImportUsesDeclaredPackageName(t *testing.T) {
	root := newFixtureRepo(t, map[string]string{
		"internal/ctor/v2/ctor.go": `package ctor
func New() any { return nil }
`,
		"internal/x/x.go": `package x
import "mcp-local-hub/internal/ctor/v2"
func F() { _ = ctor.New() }
`,
	})
	policy := mustLoadPolicyForTest(t)
	policy.SourceRoots = []string{"internal"}
	policy.APIConstructors = []SymbolRule{{ImportPath: "mcp-local-hub/internal/ctor/v2", Symbol: "New"}}
	got := violationsOfKind(mustScan(t, root, policy), KindAPIConstruction)
	if len(got) != 1 || got[0].Location.Symbol != "F" {
		t.Fatalf("got=%#v, want the declared package name ctor to resolve", got)
	}
}

func TestExternalConstructorPackageRequiresExplicitAlias(t *testing.T) {
	root := newFixtureRepo(t, map[string]string{
		"internal/x/x.go": `package x
import "example.com/ctor/v2"
func F() { _ = ctor.New() }
`,
	})
	policy := mustLoadPolicyForTest(t)
	policy.SourceRoots = []string{"internal"}
	policy.APIConstructors = []SymbolRule{{ImportPath: "example.com/ctor/v2", Symbol: "New"}}
	got := violationsOfKind(mustScan(t, root, policy), KindAPIConstruction)
	if len(got) != 2 {
		t.Fatalf("got=%#v, want both unresolved-call and explicit-alias fail-closed findings", got)
	}
	seen := map[string]bool{}
	for _, violation := range got {
		seen[violation.Message] = true
	}
	if !seen["constructor example.com/ctor/v2.New is called through an unresolved unaliased import outside its allowed composition paths"] ||
		!seen["constructor package example.com/ctor/v2 must use an explicit alias because its declared package name could not be resolved from the scanned module"] {
		t.Fatalf("got=%#v, want both fail-closed findings", got)
	}
}

