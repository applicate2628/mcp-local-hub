func TestVerifyAcceptsWorkerClassifiedOnlyInRegistry(t *testing.T) {
	violation := sampleViolation("worker", 0)
	violation.Kind = KindWorker
	violation.Fingerprint = Fingerprint(violation)

	workers := Workers{SchemaVersion: 1, Entries: []WorkerRecord{{
		Fingerprint:  violation.Fingerprint,
		Component:    "archguard",
		Owner:        "architecture",
		Start:        "F",
		Cancel:       "context cancellation",
		Join:         "wait group",
		BoundedBy:    "request deadline",
		ContractTest: "worker_test.go",
		WorkPackage:  "WP-11A",
	}}}
	got := Verify(
		reportOf(violation),
		Baseline{SchemaVersion: 1, GeneratedFrom: "base"},
		workers,
		VerifyOptions{Now: mustDate(t, "2026-08-25")},
	)
	if !got.OK() || len(got.New) != 0 {
		t.Fatalf("verification=%#v, want registry-only worker classification to pass", got)
	}
}

func TestGeneratedMarkerInsideBlockCommentDoesNotSuppressProductionRules(t *testing.T) {
	root := newFixtureRepo(t, map[string]string{
		"internal/x/x.go": `/*
// Code generated by example. DO NOT EDIT.
*/
package x

var mutable = 1
`,
	})
	policy := mustLoadPolicyForTest(t)
	policy.SourceRoots = []string{"internal"}
	got := violationsOfKind(mustScan(t, root, policy), KindMutableGlobal)
	if len(got) != 1 || got[0].Location.Symbol != "mutable" {
		t.Fatalf("got=%#v, block-comment text must not mark a file generated", got)
	}
}

